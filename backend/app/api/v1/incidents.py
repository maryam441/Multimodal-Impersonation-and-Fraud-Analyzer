"""
Official FIA Cyber Crime Incidents & Legal Affidavits Router.
Manages formal complaint registries, PECA 2016 statutory filings, and downloadable evidence dossiers.
"""

from typing import Optional, List, Dict, Any
from fastapi import APIRouter, Depends, HTTPException, Response
from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select

from backend.app.db.session import get_db
from backend.app.db.models import FIAIncidentReport, Case
from backend.app.services.fia_reporting_service import FIAReportingService

router = APIRouter(prefix="/incidents", tags=["FIA Incidents Registry"])
fia_service = FIAReportingService()


class DirectIncidentReportRequest(BaseModel):
    case_id: str = Field(..., description="Case ID generated by ambient scan or manual analysis")
    user_confirmed: bool = Field(..., description="Human authorization confirmation flag")
    operator_notes: Optional[str] = Field(None, description="Investigator remarks or victim notes")
    source: str = Field("whatsapp", description="Platform source: 'whatsapp', 'gmail', 'web', 'sms'")
    accused_identifier: Optional[str] = Field(None, description="Accused phone, URL, or sender identity")


@router.get("")
async def list_fia_incidents(limit: int = 50, db: AsyncSession = Depends(get_db)):
    """Lists all registered FIA cyber crime incident reports with tracking reference numbers."""
    stmt = select(FIAIncidentReport).order_by(FIAIncidentReport.created_at.desc()).limit(limit)
    rows = (await db.execute(stmt)).scalars().all()

    return [
        {
            "id": r.id,
            "reference_no": r.reference_no,
            "case_id": r.case_id,
            "accused_identifier": r.accused_identifier,
            "platform_source": r.platform_source,
            "risk_score": r.risk_score,
            "risk_category": r.risk_category,
            "statutory_sections": r.statutory_sections,
            "sha256_digest": r.sha256_digest,
            "status": r.status,
            "created_at": r.created_at.isoformat()
        }
        for r in rows
    ]


@router.get("/{reference_no}")
async def get_fia_incident(reference_no: str, db: AsyncSession = Depends(get_db)):
    """Retrieves full official FIA complaint report including complete legal affidavit."""
    stmt = select(FIAIncidentReport).where(FIAIncidentReport.reference_no == reference_no)
    report = (await db.execute(stmt)).scalars().first()
    if not report:
        raise HTTPException(status_code=404, detail="FIA incident report reference not found")

    return {
        "id": report.id,
        "reference_no": report.reference_no,
        "case_id": report.case_id,
        "accused_identifier": report.accused_identifier,
        "platform_source": report.platform_source,
        "risk_score": report.risk_score,
        "risk_category": report.risk_category,
        "statutory_sections": report.statutory_sections,
        "evidence_summary": report.evidence_summary,
        "complaint_text": report.complaint_text,
        "sha256_digest": report.sha256_digest,
        "operator_notes": report.operator_notes,
        "status": report.status,
        "created_at": report.created_at.isoformat()
    }


@router.get("/{reference_no}/download")
async def download_fia_affidavit(reference_no: str, db: AsyncSession = Depends(get_db)):
    """Downloads plain-text legal complaint affidavit for direct submission to FIA NR3C."""
    stmt = select(FIAIncidentReport).where(FIAIncidentReport.reference_no == reference_no)
    report = (await db.execute(stmt)).scalars().first()
    if not report:
        raise HTTPException(status_code=404, detail="FIA incident report reference not found")

    filename = f"{reference_no}.txt"
    headers = {
        "Content-Disposition": f'attachment; filename="{filename}"'
    }
    return Response(content=report.complaint_text, media_type="text/plain; charset=utf-8", headers=headers)


@router.post("/direct-report")
async def create_direct_incident_report(payload: DirectIncidentReportRequest, db: AsyncSession = Depends(get_db)):
    """
    Direct Human-in-the-Loop submission endpoint for ambient alerts (WhatsApp Web / Gmail extension).
    Registers official complaint and returns official FIA tracking number immediately.
    """
    if not payload.user_confirmed:
        raise HTTPException(
            status_code=400,
            detail="Human verification required: Submission halted by Human-in-the-Loop safety gate."
        )

    try:
        result = await fia_service.register_fia_complaint(
            case_id=payload.case_id,
            db=db,
            operator_notes=payload.operator_notes,
            complainant_source=payload.source,
            override_accused=payload.accused_identifier
        )
        return result
    except ValueError as e:
        raise HTTPException(status_code=404, detail=str(e))
